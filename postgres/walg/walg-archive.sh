#!/bin/sh
# =============================================================================
# archive_command. Аргумент — %p (шлях до сегмента WAL відносно PGDATA).
#
# Тут свідомо НЕМАЄ жодних повторів і жодного «на всяк випадок exit 0»:
# archive_command, який брехливо повертає нуль, — це втрачений WAL і
# непридатний до PITR архів, причому непомітно. Якщо wal-push упав, сервер має
# лишити сегмент у pg_wal і повторити сам.
#
# Єдиний випадок, коли скрипт нічого не робить, — коли архівування вимкнене
# (порожній WALG_S3_PREFIX). Але тоді до нього не дійде й черга: entrypoint
# рендерить `archive_mode = off`. Перевірка лишається другим рубежем на
# випадок ручного `ALTER SYSTEM SET archive_mode` без налаштованого сховища —
# інакше pg_wal ріс би до заповнення диска.
# =============================================================================
set -eu

[ -n "${WALG_S3_PREFIX:-}" ] || exit 0

exec /usr/local/bin/walg wal-push "$1"
