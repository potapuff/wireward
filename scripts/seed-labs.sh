#!/usr/bin/env bash
# =============================================================================
# Заводить лабораторні з текстового файлу (П0.5).
#
#   ./scripts/seed-labs.sh labs/2026-осінь.md            — показати, що вийде
#   ./scripts/seed-labs.sh labs/2026-осінь.md --apply    — записати
#
# Формат файлу описано у front/app/labfile.py. Ідемпотентно за назвою лаби:
# повторний запуск оновлює, а не дублює, тож виправлення зразка — це правка
# файлу і повторний запуск.
#
# Чому файл, а не форма в адмінці: зразки викладача — такий самий матеріал
# курсу, як умови задач. Їх правлять, порівнюють версії й переносять між
# семестрами, а в базі історії немає.
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."

FILE="${1:?вкажіть файл: ./scripts/seed-labs.sh labs/….md [--apply]}"
shift || true
[[ -f "$FILE" ]] || { echo "немає файлу: $FILE" >&2; exit 2; }

docker compose exec -T front python -m app.labfile "$@" < "$FILE"
